CREATE TABLE "TiposUnidad" (
    "idTipoUnidad" INTEGER PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE "Unidades" (
    "idUnidad" INTEGER PRIMARY KEY,
    "idTipoUnidad" INTEGER NOT NULL REFERENCES "TiposUnidad" ("idTipoUnidad"),
    interno VARCHAR(30) NOT NULL UNIQUE,
    patente VARCHAR(20) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL
        CHECK (estado IN ('Operativa', 'En taller', 'Parada', 'Alquilada', 'Baja')),
    kilometraje INTEGER NOT NULL CHECK (kilometraje >= 0)
);

CREATE TABLE "Choferes" (
    "idChofer" INTEGER PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    "numeroLicencia" VARCHAR(50) NOT NULL,
    "vencimientoLicencia" DATE,
    activo BOOLEAN NOT NULL
);

CREATE TABLE "AsignacionesChofer" (
    "idAsignacionChofer" INTEGER PRIMARY KEY,
    "idUnidad" INTEGER NOT NULL REFERENCES "Unidades" ("idUnidad"),
    "idChofer" INTEGER NOT NULL REFERENCES "Choferes" ("idChofer"),
    "fechaInicio" TIMESTAMP NOT NULL,
    "fechaFin" TIMESTAMP,
    CHECK ("fechaFin" IS NULL OR "fechaFin" >= "fechaInicio")
);

CREATE TABLE "TiposDocumento" (
    "idTipoDocumento" INTEGER PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE "DocumentosUnidad" (
    "idDocumentoUnidad" INTEGER PRIMARY KEY,
    "idUnidad" INTEGER NOT NULL REFERENCES "Unidades" ("idUnidad"),
    "idTipoDocumento" INTEGER NOT NULL REFERENCES "TiposDocumento" ("idTipoDocumento"),
    "fechaEmision" DATE,
    "fechaVencimiento" DATE,
    UNIQUE ("idUnidad", "idTipoDocumento")
);

-- El sistema de gestión envía el tipo de combustible como texto: el catálogo genera sus propios identificadores.
CREATE TABLE "TiposCombustible" (
    "idTipoCombustible" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE "CargasCombustible" (
    "idCargaCombustible" INTEGER PRIMARY KEY,
    "idUnidad" INTEGER NOT NULL REFERENCES "Unidades" ("idUnidad"),
    "idChofer" INTEGER REFERENCES "Choferes" ("idChofer"),
    "idTipoCombustible" INTEGER NOT NULL REFERENCES "TiposCombustible" ("idTipoCombustible"),
    fecha TIMESTAMP NOT NULL,
    cantidad DECIMAL(12, 3) NOT NULL CHECK (cantidad > 0),
    "unidadMedida" VARCHAR(3) NOT NULL CHECK ("unidadMedida" IN ('L', 'm³')),
    kilometraje INTEGER NOT NULL CHECK (kilometraje >= 0),
    lugar VARCHAR(200),
    fuente VARCHAR(30)
);
